-- Offline profile contract: runtime is built-in; no local envi/hcmux/T3/plugins.
assert(vim.o.loadplugins == false)
assert(vim.o.modeline == false)
assert(vim.o.exrc == false)
assert(vim.o.swapfile == false)
assert(vim.o.undofile == false)
assert(vim.o.shadafile == "NONE")
assert(vim.o.clipboard == "")
assert(vim.o.termguicolors == false, "RGB is opt-in after pilot E2E")
assert(vim.o.number and vim.o.ignorecase and vim.o.smartcase)
assert(vim.fn.exists(":EnviRemote") == 0)
for module, _ in pairs(package.loaded) do
  assert(not module:match("^hcmux") and not module:match("^lazy") and not module:match("^plugins"), module)
end
local filename = assert(vim.env.EDITOR_FIXTURE)
vim.cmd.edit(vim.fn.fnameescape(filename))
vim.api.nvim_buf_set_lines(0, 0, -1, false, { "offline alpha", "needle beta" })
vim.cmd.write()
vim.cmd("edit!")
assert(vim.api.nvim_buf_get_lines(0, 0, 1, false)[1] == "offline alpha")
assert(vim.fn.search("needle", "w") == 2)
vim.cmd.vsplit()
assert(#vim.api.nvim_list_wins() == 2)
vim.cmd.only()
print("remote editor offline tests passed")
