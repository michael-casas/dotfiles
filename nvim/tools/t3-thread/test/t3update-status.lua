-- B1 :T3Status: one async notice with reachability, runtime, marker, clients.
local F = dofile("nvim/tools/t3-thread/test/support/t3update-fixture.lua")
local U = require("hcmux.t3update")

F.case("async: returns before the probe answers, then one notice", function()
  F.reset()
  F.server(false)
  U.status()
  assert(#F.notices == 0, "status must not block on the probe")
  F.wait_notice("^T3:")
  vim.wait(50)
  assert(#F.notices == 1, "exactly one notice")
end)

F.case("probe: T3_URL, environment endpoint, 2 s timeout", function()
  F.reset()
  F.server(true)
  U.status()
  F.wait_notice("^T3:")
  local curl = F.of("curl")[1]
  assert(curl, "curl probe")
  local argv = table.concat(curl.argv, " ")
  assert(argv:find("http://127.0.0.1:39999/.well-known/t3/environment", 1, true), argv)
  assert(argv:find("-m 2", 1, true), argv)
end)

F.case("everything absent", function()
  F.reset()
  F.server(false)
  U.status()
  F.wait_notice("^T3:")
  local text = F.last()
  assert(text:find("unreachable"), text)
  assert(text:find("no server%-runtime%.json"), text)
  assert(text:find("no update in progress"), text)
  assert(text:find("0 client buffers, 0 client processes running"), text)
end)

F.case("up, runtime fields only, marker with seconds left, clients", function()
  F.reset()
  F.server(true)
  F.set_runtime(4242, "0.1.11-nightly", { authToken = "SECRET-TOKEN", host = "example.invalid" })
  F.set_marker(30)
  F.client("t3-a", "live")
  F.client("t3-b", "finished")
  F.client("t3-c", "live")
  U.status()
  F.wait_notice("^T3:")
  local text = F.last()
  assert(text:find("server up"), text)
  assert(text:find("v0.1.11-nightly", 1, true), text)
  assert(text:find("pid 4242"), text)
  assert(text:find("2026-11-18T02:33:13Z", 1, true), text)
  assert(not text:find("SECRET") and not text:find("example.invalid"), "only non-secret fields: " .. text)
  local left = tonumber(text:match("update in progress %((%d+) s left%)"))
  assert(left and left >= 28 and left <= 30, text)
  assert(text:find("3 client buffers, 2 client processes running"), text)
  assert(not text:find("connected") and not text:find("live"), "process liveness only: " .. text)
end)

F.case("expired marker counts as absent", function()
  F.reset()
  F.server(true)
  F.set_marker(-12)
  U.status()
  F.wait_notice("^T3:")
  assert(F.last():find("no update in progress %(marker expired %d+ s ago%)"), F.last())
end)

F.case("malformed marker is in progress until mtime + 60 s, then absent", function()
  F.reset()
  F.server(true)
  F.write(F.marker, "{half")
  U.status()
  F.wait_notice("^T3:")
  local left = tonumber(F.last():match("update in progress %((%d+) s left%)"))
  assert(left and left >= 58 and left <= 60, F.last())
  F.notices = {}
  local old = os.time() - 90
  vim.uv.fs_utime(F.marker, old, old)
  U.status()
  F.wait_notice("^T3:")
  assert(F.last():find("no update in progress %(marker expired"), F.last())
end)

F.case("unreadable runtime file never errors", function()
  F.reset()
  F.server(true)
  F.write(F.runtime, "{not json")
  U.status()
  F.wait_notice("^T3:")
  assert(F.last():find("server%-runtime%.json unreadable"), F.last())
end)

F.case(":T3Status is registered and runs the same check", function()
  F.reset()
  F.server(true)
  U.setup()
  vim.cmd("T3Status")
  F.wait_notice("^T3: server up")
end)

F.done()
