-- features/04-insert-finalize.feature: every scenario (WP4).
local H = require("hcmux.sudoku.test.harness")
local W = require("hcmux.sudoku.test.wp4")
local api = vim.api
H.boot()
W.motion_stand_ins()

H.scenario("i, a digit and <Enter> commit an entry", function()
  H.background()
  H.place(1, 3)
  H.type("i")
  H.ok(H.footer():find("^INSERT  "), "after i the footer mode reads INSERT: " .. H.footer())
  H.eq(H.state().mode, "insert", "state().mode after i")
  H.type("4")
  local s = H.state()
  H.eq(s.draft, 4, "state().draft is the staged 4")
  H.eq(W.overlay(1, 3), { { "4", "EnviSudokuDraft" } }, "R1C3 shows a draft 4 styled EnviSudokuDraft")
  H.ok(H.groups(1, 3).EnviSudokuDraft, "R1C3's cell carries EnviSudokuDraft")
  H.eq(s.board[1][3], 0, "state().board[1][3] is still 0")
  H.eq(H.lines()[2]:sub(1, 22), " ┃ 5 │ 3 │   ┃", "the board text still shows R1C3 empty under the draft")
  H.type("<CR>")
  s = H.state()
  H.eq(s.board[1][3], 4, "R1C3 holds 4")
  H.ok(H.groups(1, 3).EnviSudokuEntry and not H.groups(1, 3).EnviSudokuDraft, "R1C3 is styled EnviSudokuEntry")
  H.eq(W.overlay(1, 3), {}, "the draft overlay is gone")
  H.eq(H.lines()[2]:sub(1, 22), " ┃ 5 │ 3 │ 4 ┃", "the board text shows the 4 at R1C3")
  H.ok(H.footer():find("^NORMAL  R1C3  "), "the footer reads NORMAL at R1C3: " .. H.footer())
  H.eq(s.cursor, { r = 1, c = 3 }, "the cursor box is still on R1C3")
  H.eq(s.draft, nil, "no draft is left")
end)

H.scenario("a second digit replaces the draft", function()
  H.background()
  H.place(1, 3)
  H.type("i4")
  H.eq(H.state().draft, 4, "setup: draft 4")
  H.type("2")
  H.eq(H.state().draft, 2, "the second digit replaces the draft")
  H.eq(W.overlay(1, 3), { { "2", "EnviSudokuDraft" } }, "R1C3 shows the draft 2")
  H.type("<CR>")
  H.eq(H.state().board[1][3], 2, "R1C3 holds 2")
  H.eq(H.state().undo, 1, "one committed step")
end)

H.scenario("<Enter> with no draft changes nothing", function()
  H.background()
  H.place(1, 3)
  H.type("i")
  H.type("<CR>")
  local s = H.state()
  H.eq(s.board, H.CLASSIC, "R1C3 is empty and the board equals the fixture")
  H.ok(H.footer():find("^NORMAL  "), "the footer mode reads NORMAL: " .. H.footer())
  H.eq(s.undo, 0, "state().undo is 0")
end)

H.scenario("<Esc> discards the draft", function()
  H.background()
  H.place(1, 3)
  H.type("i7")
  H.eq(H.state().draft, 7, "setup: draft 7")
  H.type("<Esc>")
  local s = H.state()
  H.eq(s.board[1][3], 0, "R1C3 is empty")
  H.eq(s.draft, nil, "the draft is discarded")
  H.eq(W.overlay(1, 3), {}, "no draft overlay")
  H.ok(H.footer():find("^NORMAL  "), "the footer mode reads NORMAL: " .. H.footer())
  H.eq(s.undo, 0, "state().undo is 0")
  -- A discarded draft never comes back: <Enter> after re-entering commits nothing.
  H.type("i")
  H.type("<CR>")
  H.eq(H.state().board[1][3], 0, "re-entering INSERT starts without the old draft")
end)

H.scenario("given tiles are immutable", function()
  H.background()
  local seen = W.notices()
  H.type("i")
  H.ok(H.footer():find("GIVEN", 1, true), "in INSERT the footer flags the given: " .. H.footer())
  H.type("3")
  H.eq(H.state().draft, nil, "no draft is staged over a given")
  H.type("<CR>")
  local s = H.state()
  H.eq(s.board[1][1], 5, "R1C1 still holds 5")
  H.ok(s.givens[1][1], "R1C1 is still a given")
  H.ok(H.groups(1, 1).EnviSudokuGiven, "R1C1 is still styled EnviSudokuGiven")
  H.eq(s.board, H.CLASSIC, "the board equals the fixture")
  H.eq(s.undo, 0, "state().undo is 0")
  local said = false
  for _, n in ipairs(seen) do
    said = said or (n.msg:lower():find("given", 1, true) ~= nil and n.level < vim.log.levels.ERROR)
  end
  H.ok(said, "a notice says the tile is a given: " .. vim.inspect(seen))
end)

H.scenario("an entry can be overwritten by a later insert", function()
  H.background()
  W.commit(1, 3, 4)
  H.type("i2")
  H.type("<CR>")
  local s = H.state()
  H.eq(s.board[1][3], 2, "R1C3 holds 2")
  H.eq(s.undo, 2, "state().undo is 2")
end)

H.scenario("insert mode ignores non-digit keys and 0", function()
  H.background()
  H.place(1, 3)
  H.type("i")
  H.type("a0x")
  local s = H.state()
  H.eq(s.draft, nil, "no draft is staged")
  H.eq(s.board, H.CLASSIC, "the board is unchanged")
  H.eq(s.mode, "insert", "still in insert mode")
  H.ok(H.footer():find("^INSERT  "), "the footer mode still reads INSERT: " .. H.footer())
  H.eq(api.nvim_get_mode().mode, "n", "nothing was typed into the buffer (Neovim stays in Normal)")
end)

H.scenario("hjkl inside insert mode are ignored, not typed and not moved", function()
  H.background()
  H.place(1, 3)
  H.type("i")
  H.type("l")
  local s = H.state()
  H.eq(s.cursor, { r = 1, c = 3 }, "the cursor box is still on R1C3")
  H.eq(s.hl.cursor, { { r = 1, c = 3 } }, "the outline is still drawn on R1C3")
  H.eq(s.mode, "insert", "still in insert mode")
  H.eq(s.draft, nil, "nothing was staged")
  for _, lhs in ipairs({ "h", "j", "k" }) do
    H.type(lhs)
    H.eq(H.state().cursor, { r = 1, c = 3 }, lhs .. " does not move either")
  end
  H.type("<Esc>")
  H.type("l")
  H.eq(H.state().cursor, { r = 1, c = 4 }, "back in NORMAL, l moves again (the motion is not broken)")
end)

-- Q4 support (not a contract scenario): the detection WP5's SOLVED timer reads.
H.scenario("solved detection: a full valid board is solved, a gap or a conflict is not", function()
  local editing = require("hcmux.sudoku.ext.editing")
  local solution = {}
  for r, row in ipairs(vim.split("534678912 672195348 198342567 859761423 426853791 713924856 961537284 287419635 345286179", " ")) do
    solution[r] = {}
    for c = 1, 9 do
      solution[r][c] = tonumber(row:sub(c, c))
    end
  end
  H.ok(editing.solved(solution), "the README's solution is solved")
  H.eq(editing.conflicts(solution), {}, "and has no conflicts")
  local gap = vim.deepcopy(solution)
  gap[5][5] = 0
  H.ok(not editing.solved(gap), "a gap is not solved")
  local swap = vim.deepcopy(solution)
  swap[1][1], swap[1][2] = swap[1][2], swap[1][1] -- rows stay valid, columns break
  H.ok(not editing.solved(swap), "a column conflict is not solved")
  H.ok(#editing.conflicts(swap) > 0, "and is flagged")
end)

H.finish()
