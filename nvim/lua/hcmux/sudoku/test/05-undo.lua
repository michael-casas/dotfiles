-- features/05-undo.feature: every scenario (WP4).
local H = require("hcmux.sudoku.test.harness")
local W = require("hcmux.sudoku.test.wp4")
H.boot()
W.motion_stand_ins()
W.search_stand_ins()

H.scenario("u undoes the last committed entry", function()
  H.background()
  W.commit(1, 3, 4)
  W.commit(1, 4, 6)
  H.eq(H.state().undo, 2, "setup: two steps")
  H.type("u")
  local s = H.state()
  H.eq({ s.board[1][3], s.board[1][4] }, { 4, 0 }, "R1C4 is empty and R1C3 holds 4")
  H.eq(s.undo, 1, "one step left")
  H.type("u")
  s = H.state()
  H.eq(s.board, H.CLASSIC, "R1C3 is empty (the board is the fixture again)")
  H.eq({ s.undo, s.redo }, { 0, 2 }, "both steps moved to redo")
  H.ok(H.lines()[2]:find("^ ┃ 5 │ 3 │   ┃   │ 7 │"), "R1C3 and R1C4 are drawn empty: " .. H.lines()[2])
end)

H.scenario("undo moves the cursor box to the changed tile", function()
  H.background()
  W.commit(1, 3, 4)
  H.place(9, 1)
  H.type("u")
  local s = H.state()
  H.eq(s.board[1][3], 0, "the entry is undone")
  H.eq(s.cursor, { r = 1, c = 3 }, "the cursor box is on R1C3")
  H.eq(s.hl.cursor, { { r = 1, c = 3 } }, "the outline is drawn on R1C3")
end)

H.scenario("navigation, search and canceled drafts are not undo steps", function()
  H.background()
  W.commit(1, 3, 4)
  H.type("3j")
  H.eq(H.state().cursor, { r = 4, c = 3 }, "3j moved")
  H.type("/9<CR>")
  H.eq(H.state().mode, "normal", "the search was accepted")
  H.type("i7<Esc>")
  local s = H.state()
  H.eq({ s.mode, s.board[4][3], s.undo }, { "normal", 0, 1 }, "the canceled draft left no step")
  H.type("u")
  H.eq(H.state().board[1][3], 0, "R1C3 is empty")
  H.eq(H.state().undo, 0, "no history remains")
end)

H.scenario("u with nothing to undo is a harmless no-op", function()
  H.background()
  local seen = W.notices()
  vim.v.errmsg = ""
  H.type("u")
  local s = H.state()
  H.eq(s.board, H.CLASSIC, "the board equals the fixture")
  H.eq({ s.undo, s.redo }, { 0, 0 }, "history is empty")
  H.ok(s.open and s.focused, "the popover is still open and focused")
  H.eq(vim.v.errmsg, "", "no error")
  for _, n in ipairs(seen) do
    H.ok(n.level < vim.log.levels.ERROR, "the notice is not an error: " .. n.msg)
  end
  H.ok(#seen == 1 and seen[1].msg:find("oldest", 1, true), "an 'Already at oldest change' notice: " .. vim.inspect(seen))
end)

H.scenario("a count undoes several steps", function()
  H.background()
  W.commit(1, 3, 4)
  W.commit(1, 4, 6)
  W.commit(1, 6, 8)
  H.type("2u")
  local s = H.state()
  H.eq({ s.board[1][3], s.board[1][4], s.board[1][6] }, { 4, 0, 0 }, "R1C6 and R1C4 are empty and R1C3 holds 4")
  H.eq({ s.undo, s.redo }, { 1, 2 }, "two steps undone")
end)

H.scenario("<C-r> redoes, and a new edit clears redo", function()
  H.background()
  W.commit(1, 3, 4)
  H.type("u")
  H.eq(H.state().board[1][3], 0, "setup: undone")
  H.place(5, 5)
  H.type("<C-r>")
  local s = H.state()
  H.eq(s.board[1][3], 4, "R1C3 holds 4")
  H.eq(s.cursor, { r = 1, c = 3 }, "redo puts the cursor box on the changed tile")
  H.eq({ s.undo, s.redo }, { 1, 0 }, "the step is back in undo")
  H.type("u")
  W.commit(1, 4, 2)
  H.eq(H.state().redo, 0, "the new edit cleared redo")
  H.type("<C-r>")
  s = H.state()
  H.eq({ s.board[1][3], s.board[1][4] }, { 0, 2 }, "R1C3 is empty and R1C4 holds 2")
end)

H.scenario("paste and clear are undoable like inserts", function()
  H.background()
  H.type("y")
  H.place(1, 3)
  H.type("p")
  H.eq(H.state().board[1][3], 5, "setup: pasted 5")
  H.type("u")
  H.eq(H.state().board[1][3], 0, "R1C3 is empty")
  -- Clear (x, Q16) is one undo step too.
  W.commit(1, 3, 4)
  H.type("x")
  H.eq({ H.state().board[1][3], H.state().undo }, { 0, 2 }, "x cleared R1C3 as one step")
  H.type("u")
  H.eq(H.state().board[1][3], 4, "u brings the cleared 4 back")
end)

-- Q16 (in force, no scenario yet): x on an empty tile or a given changes nothing.
H.scenario("x on an empty tile or a given leaves the board and history intact", function()
  H.background()
  H.type("x")
  H.place(1, 3)
  H.type("x")
  local s = H.state()
  H.eq(s.board, H.CLASSIC, "the board equals the fixture")
  H.eq(s.undo, 0, "no history")
end)

H.finish()
